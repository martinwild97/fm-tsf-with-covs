import logging
import os
import shutil
import time
import uuid
import warnings
import pandas as pd
from typing import Any, Dict, List, Union

from autogluon.timeseries import TimeSeriesDataFrame, TimeSeriesPredictor

from src.models.schemas import ModelInput, ModelOutput

# Suppress warnings from the autogluon library to prevent verbose output during execution.
warnings.filterwarnings("ignore")

# Initialize a common logger for all forecasting models.
logger: logging.Logger = logging.getLogger("Forecast")


class OtherModels:
    """
    A forecaster class that encapsulates various time series models not covered
    by the `BaselineModels`, specifically leveraging AutoGluon's capabilities
    for tabular regression models (e.g., LightGBM) and specialized deep learning
    models like Chronos.
    """

    def _prep_predictor(self, model_input: ModelInput) -> TimeSeriesPredictor:
        """
        Prepares and configures a `TimeSeriesPredictor` instance from AutoGluon.

        This method sets up the common parameters for the predictor, such as
        prediction length, quantile levels, target column, verbosity, logging,
        and caching behavior.

        Parameters
        ----------
        model_input : ModelInput
            An instance of `ModelInput` containing necessary forecasting parameters
            like forecast horizon and quantile level.

        Returns
        -------
        TimeSeriesPredictor
            A configured AutoGluon `TimeSeriesPredictor` instance, ready for fitting.
        """
        # Define quantile levels for prediction intervals. AutoGluon expects three levels:
        # lower bound (1 - quantile), median (0.5), and upper bound (quantile).
        quantile_lower: float = 1 - model_input.quantile
        quantile_median: float = 0.5
        quantile_upper: float = model_input.quantile

        predictor: TimeSeriesPredictor = TimeSeriesPredictor(
            prediction_length=model_input.forecast_horizon,
            quantile_levels=[quantile_lower, quantile_median, quantile_upper],
            target="y",  # Default target column name for AutoGluon's TimeSeriesDataFrame
            verbosity=0,  # Suppress AutoGluon verbose output
            log_to_file=False,  # Disable logging to a file for this predictor instance
            cache_predictions=False,  # Do not cache predictions to disk
        )
        return predictor

    def _to_model_output(self, forecast: TimeSeriesDataFrame, quantile: float, forecast_time: float) -> ModelOutput:
        """
        Converts an AutoGluon `TimeSeriesDataFrame` forecast into a `ModelOutput` instance.
        This method also handles cleanup of AutoGluon's temporary model directory.

        Parameters
        ----------
        forecast : TimeSeriesDataFrame
            The forecast results generated by AutoGluon.
        quantile : float
            The quantile level (e.g., 0.9 for 90%) used for calculating prediction intervals.
        forecast_time : float
            The time taken to generate the forecast, in seconds.

        Returns
        -------
        ModelOutput
            A `ModelOutput` instance containing the processed forecast data and metadata.
        """
        # Clean up AutoGluon's temporary model directory to free up disk space.
        autogluon_temp_dir: str = "AutogluonModels"
        if os.path.exists(autogluon_temp_dir):
            try:
                shutil.rmtree(autogluon_temp_dir)
                logger.debug(f"Removed temporary AutoGluon directory: {autogluon_temp_dir}")
            except OSError as e:
                logger.warning(f"Failed to remove AutoGluon directory {autogluon_temp_dir}: {e}")

        # Define the column names for point forecast, lower bound, and upper bound
        # as expected by the ModelOutput.from_df method.
        # AutoGluon uses string representations of quantiles for column names.
        median_col_name: str = str(0.5)
        lower_bound_col_name: str = str(1 - quantile)
        upper_bound_col_name: str = str(quantile)

        # Convert the forecast DataFrame to a format suitable for ModelOutput.
        # AutoGluon's `item_id` corresponds to our `unique_id` concept for multiple series.
        return ModelOutput(forecast_successful=True).from_df(
            forecast_df=forecast.reset_index(),  # Ensure 'item_id' and 'timestamp' are columns
            column_names=(median_col_name, lower_bound_col_name, upper_bound_col_name),
            item_id_column="item_id",  # Specify the column identifying individual time series
            metadata={"forecast_time_seconds": forecast_time},
        )

    def _forecast_regressor(self, model_input: ModelInput, model_type: str = "GBM") -> ModelOutput:
        """
        Generates forecasts using a tabular regression model (e.g., LightGBM)
        from AutoGluon TimeSeries.

        Parameters
        ----------
        model_input : ModelInput
            An instance of `ModelInput` containing the time series data and covariates.
        model_type : str, default="GBM"
            The type of regression model to use (e.g., "GBM" for LightGBM, "XGB" for XGBoost).

        Returns
        -------
        ModelOutput
            A `ModelOutput` instance containing the forecast results or error information.
        """
        try:
            # Convert the input DataFrame into AutoGluon's `TimeSeriesDataFrame` format.
            autogluon_df: TimeSeriesDataFrame = model_input.get_autogluon_input()

            # Prepare the AutoGluon predictor instance.
            predictor: TimeSeriesPredictor = self._prep_predictor(model_input)

            # Define hyperparameters for the specified tabular model.
            # `DirectTabular` indicates a direct regression approach on time series features.
            hyperparameters: Dict[str, Dict[str, Dict[Any, Any]]] = {"DirectTabular": {model_type: {}}}

            # Record the start time for performance measurement.
            start_time: float = time.time()

            forecast: TimeSeriesDataFrame
            if model_input.future_covs:
                # If future covariates are present, split data for training and known covariates
                # during prediction. `train_test_split` here is used to separate the main training
                # data from the future part which contains `known_covariates`.
                train_data, test_data = autogluon_df.train_test_split(model_input.forecast_horizon)
                predictor.known_covariates_names = model_input.future_covs
                predictor.fit(train_data, hyperparameters=hyperparameters)
                # Predict using the trained model and providing future known covariates.
                forecast = predictor.predict(train_data, known_covariates=test_data.drop(columns=['y']))
            else:
                # If no future covariates, fit on the full data and predict directly.
                predictor.fit(autogluon_df, hyperparameters=hyperparameters)
                forecast = predictor.predict(autogluon_df)

            # Calculate the total time taken for forecasting.
            forecast_time_seconds: float = time.time() - start_time

            # Convert the AutoGluon forecast to `ModelOutput` format and clean up.
            return self._to_model_output(forecast, model_input.quantile, forecast_time_seconds)

        except Exception as e:
            # Log any exceptions and return a failed `ModelOutput`.
            log_id: str = str(uuid.uuid4())
            logger.exception(
                f"Error in regressor model forecast (Log ID: {log_id}): {e}",
                extra={"log_id": log_id},
            )
            return ModelOutput(forecast_successful=False, error_log_id=log_id)

    def _forecast_chronos(self, model_input: ModelInput, model_type: str = "bolt_base", regressor: str = "LR") -> ModelOutput:
        """
        Generates forecasts using the Chronos model (a transformer-based time series model)
        from AutoGluon TimeSeries.

        This method handles imputation of missing past covariates if necessary by
        forecasting them first.

        Parameters
        ----------
        model_input : ModelInput
            An instance of `ModelInput` containing the time series data,
            past/future covariates, and other parameters.
        model_type : str, default="bolt_base"
            The specific Chronos model variant or preset to use (e.g., "bolt_base", "tiny").
        regressor : str, default="LR"
            The type of regressor to use for covariate regression within Chronos
            (e.g., "LR" for Linear Regression, "GBM" for LightGBM).

        Returns
        -------
        ModelOutput
            A `ModelOutput` instance containing the forecast results or error information.
        """
        try:
            # Convert the input DataFrame into AutoGluon's `TimeSeriesDataFrame` format.
            autogluon_df: TimeSeriesDataFrame = model_input.get_autogluon_input()

            # Record the start time for performance measurement.
            start_time: float = time.time()

            # Handle imputation of missing past covariates by forecasting them if present.
            # This is critical as Chronos (and other deep learning models) typically don't handle NaNs well.
            if model_input.past_covs or model_input.future_covs:
                # Iterate through past covariates that might have missing values.
                for past_cov in model_input.past_covs:
                    # Identify rows with missing values in the current past covariate.
                    missing_indices = autogluon_df[autogluon_df[past_cov].isna()].index
                    if not missing_indices.empty:
                        logger.info(f"Imputing missing values for past covariate '{past_cov}' using Chronos for item_ids: {autogluon_df.loc[missing_indices, 'item_id'].unique().tolist()}")
                        # Create a temporary predictor for the current past covariate.
                        # Target is now the past_covariate itself.
                        temp_predictor: TimeSeriesPredictor = self._prep_predictor(model_input)
                        temp_predictor.target = past_cov
                        # Fit Chronos using the specified preset to impute missing past covariate values.
                        temp_predictor.fit(autogluon_df, presets=model_type)
                        # Predict the missing values of the past covariate.
                        imputed_forecast = temp_predictor.predict(autogluon_df)
                        # Fill the missing values in the original DataFrame with the median forecast.
                        autogluon_df.loc[missing_indices, past_cov] = imputed_forecast[str(0.5)].values
                        logger.debug(f"Imputed {len(missing_indices)} missing values for '{past_cov}'.")

                # After (potential) imputation, prepare data for the main Chronos forecast.
                # Split data into training and a portion containing future known covariates.
                train_data, test_data = autogluon_df.train_test_split(model_input.forecast_horizon)
                
                # Define hyperparameters for the Chronos model.
                # `model_path` refers to the pre-trained Chronos model.
                # `target_scaler` standardizes the target variable.
                # `covariate_regressor` specifies how covariates are incorporated.
                hyperparameters: Dict[str, Dict[str, Any]] = {
                    "Chronos": {
                        "model_path": model_type,
                        "target_scaler": "standard",
                        "covariate_regressor": regressor,
                    },
                }
                
                # Prepare the main predictor for forecasting the target variable.
                main_predictor: TimeSeriesPredictor = self._prep_predictor(model_input)
                # Inform the predictor about all known covariates (past and future).
                main_predictor.known_covariates_names = model_input.future_covs + model_input.past_covs
                
                # Fit the Chronos model.
                main_predictor.fit(train_data, hyperparameters=hyperparameters)
                
                # Generate forecasts, providing future known covariates.
                forecast = main_predictor.predict(train_data, known_covariates=test_data.drop(columns=['y']))
            else:
                # If no covariates, fit Chronos directly on the full data.
                main_predictor: TimeSeriesPredictor = self._prep_predictor(model_input)
                main_predictor.fit(autogluon_df, presets=model_type)
                forecast = main_predictor.predict(autogluon_df)

            # Calculate the total time taken for forecasting.
            forecast_time_seconds: float = time.time() - start_time

            # Convert the AutoGluon forecast to `ModelOutput` format and clean up.
            return self._to_model_output(forecast, model_input.quantile, forecast_time_seconds)

        except Exception as e:
            # Log any exceptions and return a failed `ModelOutput`.
            log_id: str = str(uuid.uuid4())
            logger.exception(
                f"Error in Chronos model forecast (Log ID: {log_id}): {e}",
                extra={"log_id": log_id},
            )
            return ModelOutput(forecast_successful=False, error_log_id=log_id)

    def forecast(self, model_input: ModelInput, model: str, **kwargs: Any) -> ModelOutput:
        """
        Dispatches the forecasting request to the appropriate internal model method
        based on the `model` string.

        Parameters
        ----------
        model_input : ModelInput
            An instance of `ModelInput` containing the time series data and parameters.
        model : str
            A string indicating which specific model type to use (e.g., "regressor", "chronos").
        **kwargs : Any
            Additional keyword arguments passed directly to the chosen internal forecasting method.
            For "regressor", this might include `model_type`.
            For "chronos", this might include `model_type` and `regressor`.

        Returns
        -------
        ModelOutput
            A `ModelOutput` instance containing the forecast results or error information.
        """
        if model == "regressor":
            return self._forecast_regressor(model_input, **kwargs)
        elif model == "chronos":
            return self._forecast_chronos(model_input, **kwargs)
        else:
            # If an unsupported model type is requested, log an error and return failure.
            log_id: str = str(uuid.uuid4())
            logger.error(
                f"Model '{model}' not supported by OtherModels class (Log ID: {log_id}).",
                extra={"log_id": log_id},
            )
            return ModelOutput(forecast_successful=False, error_log_id=log_id)


